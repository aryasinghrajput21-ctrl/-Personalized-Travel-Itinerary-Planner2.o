import React, { useEffect, useMemo } from 'react';
import { MapContainer, TileLayer, Marker, Popup, useMap } from 'react-leaflet';
import L from 'leaflet';
import { MapPin, Navigation, Clock, DollarSign } from 'lucide-react';

// Create custom colored pin markers with numbers
function createCustomPin(number, color = '#4f46e5') {
  return L.divIcon({
    className: 'custom-map-pin',
    html: `
      <div style="
        background-color: ${color};
        color: white;
        width: 32px;
        height: 32px;
        border-radius: 50% 50% 50% 0;
        transform: rotate(-45deg);
        display: flex;
        align-items: center;
        justify-content: center;
        box-shadow: 0 4px 10px rgba(0,0,0,0.3);
        border: 2px solid white;
        font-family: sans-serif;
      ">
        <span style="transform: rotate(45deg); font-weight: bold; font-size: 12px;">
          ${number}
        </span>
      </div>
    `,
    iconSize: [32, 32],
    iconAnchor: [16, 32],
    popupAnchor: [0, -32],
  });
}

// Helper component to auto-recenter map when pins change
function MapRecenter({ coords }) {
  const map = useMap();
  useEffect(() => {
    if (coords && coords.length > 0) {
      if (coords.length === 1) {
        map.setView([coords[0].lat, coords[0].lng], 13);
      } else {
        const bounds = L.latLngBounds(coords.map(c => [c.lat, c.lng]));
        map.fitBounds(bounds, { padding: [40, 40], maxZoom: 14 });
      }
    }
  }, [coords, map]);
  return null;
}

export default function InteractiveMap({ activities = [], selectedDayNumber = null }) {
  // Collect all valid coordinate markers
  const markers = useMemo(() => {
    const list = [];
    activities.forEach((act, idx) => {
      if (act.latitude && act.longitude) {
        list.push({
          ...act,
          index: idx + 1,
          lat: Number(act.latitude),
          lng: Number(act.longitude),
        });
      }
    });
    return list;
  }, [activities]);

  const defaultCenter = markers.length > 0
    ? [markers[0].lat, markers[0].lng]
    : [35.6762, 139.6503];

  return (
    <div className="w-full h-[450px] relative rounded-2xl overflow-hidden border border-slate-200 shadow-sm bg-slate-100">
      
      {markers.length === 0 ? (
        <div className="w-full h-full flex flex-col items-center justify-center p-6 text-center text-slate-500">
          <MapPin className="w-10 h-10 text-slate-400 mb-2 animate-bounce" />
          <p className="font-semibold text-slate-700">No Location Coordinates Available</p>
          <p className="text-xs text-slate-500 mt-1 max-w-sm">
            Coordinates are automatically generated by the AI for each scheduled activity.
          </p>
        </div>
      ) : (
        <>
          {/* Map Top Floating Header */}
          <div className="absolute top-3 left-3 z-[1000] bg-white/95 backdrop-blur-sm px-3.5 py-1.5 rounded-xl border border-slate-200 shadow-md flex items-center gap-2">
            <Navigation className="w-4 h-4 text-indigo-600 animate-spin-slow" />
            <span className="text-xs font-bold text-slate-800">
              {selectedDayNumber ? `Day ${selectedDayNumber} Route Map` : 'Interactive Trip Map'}
            </span>
            <span className="text-[11px] bg-indigo-50 text-indigo-700 px-2 py-0.5 rounded-full font-semibold">
              {markers.length} Stops
            </span>
          </div>

          <MapContainer
            center={defaultCenter}
            zoom={13}
            scrollWheelZoom={false}
            className="w-full h-full"
          >
            <TileLayer
              attribution='&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors'
              url="https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png"
            />
            <MapRecenter coords={markers} />

            {markers.map((item) => (
              <Marker
                key={item.id || item.index}
                position={[item.lat, item.lng]}
                icon={createCustomPin(
                  item.index,
                  item.time_slot === 'morning' ? '#f59e0b' : item.time_slot === 'afternoon' ? '#3b82f6' : '#6366f1'
                )}
              >
                <Popup className="custom-popup">
                  <div className="p-1 max-w-xs font-sans">
                    <div className="flex items-center gap-1.5 mb-1">
                      <span className="text-[10px] font-bold uppercase px-1.5 py-0.5 rounded bg-indigo-50 text-indigo-700">
                        Stop #{item.index} · {item.time_slot}
                      </span>
                    </div>
                    <h4 className="font-bold text-sm text-slate-900 leading-tight mb-1">
                      {item.title}
                    </h4>
                    <p className="text-xs text-slate-600 line-clamp-2 mb-2">
                      {item.description}
                    </p>
                    <div className="flex items-center gap-3 text-[11px] text-slate-500 pt-1 border-t border-slate-100">
                      <div className="flex items-center gap-1">
                        <Clock className="w-3 h-3 text-indigo-500" />
                        <span>{item.estimated_duration}</span>
                      </div>
                      <div className="flex items-center gap-1">
                        <DollarSign className="w-3 h-3 text-emerald-500" />
                        <span>{item.estimated_cost > 0 ? `$${item.estimated_cost}` : 'Free'}</span>
                      </div>
                    </div>
                  </div>
                </Popup>
              </Marker>
            ))}
          </MapContainer>
        </>
      )}

    </div>
  );
}

